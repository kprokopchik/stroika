    for r, what, where, h, gg in TECH_EL:
        if gg == g:
            items.append(f"{RN[r]}: {what.lower()}, {where}")
    by_room = {}
    for l in LT:
        if l["g"] == g:
            by_room.setdefault(l["room"], []).append(LAMP[l["kind"]].lower())
    for r, lst in by_room.items():
        cnt = {}
        for x in lst:
            cnt[x] = cnt.get(x, 0) + 1
        items.append(f"{RN[r]}: " + ", ".join(f"{k} ×{v}" if v > 1 else k for k, v in cnt.items()))
    n_sw = sum(1 for s in SW if s["g"] == g)
    if n_sw:
        items.append(f"Выключатели: {n_sw}")
    return items


