def kinds_text(kinds):
    s, u = kinds.count("std"), kinds.count("ups")
    parts = []
    if s:
        parts.append("розетка" if s == 1 else f"{s} розетки")
    if u:
        parts.append(("розетка" if u == 1 else f"{u} розетки") + " ИБП")
    t = " + ".join(parts)
    return t[0].upper() + t[1:]


