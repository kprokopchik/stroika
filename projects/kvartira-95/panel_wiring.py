def terminal_rows(groups):
    rows = []
    for g, (name, protection, cable, kw) in groups.items():
        feed = "SA.C.L / SA.C.N" if g == 17 else "XL / XN"
        actor = CONTROLLED[g][0] if g in CONTROLLED and CONTROLLED[g][2] == "силовой контакт L" else None
        output = (f"L через {actor} → " if actor else "") + f"X{g}.L; N → X{g}.N"
        rows.append([f"QF{g}", feed, output, f"X{g}.PE → XPE", f"W{g}: {cable}", name])
    return rows


