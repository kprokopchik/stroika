"""Таблицы соединений из общей модели щита."""
from panel_model import BANKS, BANK_OF, GROUPS, BRANCHES


def terminal_rows(groups=GROUPS):
    rows = []
    for g, (name, _, cable, _) in groups.items():
        bank = BANK_OF[g]
        _, _, neutral, comb = BANKS[bank]
        n = f"{neutral} → QF{g}.N → W{g}.N" if g == 3 else f"{neutral} → W{g}.N"
        phase = f"{comb}.L → QF{g} → " + (f"X{g}.L → ветви W{g}.*" if g in BRANCHES else f"W{g}.L напрямую")
        rows.append([f"QF{g} / {bank}", phase, n, f"XPE → W{g}.PE", f"W{g} · {cable}", name])
    rows.append(["QF22 · не установлен", "B4 → будущий QF22 → W22.L", "N4S → W22.N", "XPE → W22.PE", "резерв 3×2,5", "Бойлер, модель и место не выбраны"])
    return rows


