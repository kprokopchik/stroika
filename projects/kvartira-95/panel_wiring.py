COL = {"L": "#8A4728", "N": "#1764B0", "PE": "#18733E"}


class Drawing:
    def __init__(self, title, height):
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 {height}" role="img" aria-label="{escape(title)}">',
                      f'<rect width="760" height="{height}" fill="#FFFFFF"/>']
        self.text(380, 24, title, 17, weight=700)

    def text(self, x, y, text, size=12, anchor="middle", weight=500, color="#263238"):
        self.parts.append(S.txt(x, y, text, fs=size, font=S.SANS, anchor=anchor, weight=weight, fill=color, halo=False))

    def box(self, x, y, w, h, lines, fill="#F2F5F7", stroke="#52616B"):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{fill}" stroke="{stroke}" stroke-width="1.4"/>')
        for i, t in enumerate(lines):
            self.text(x + w / 2, y + h / 2 + (i - (len(lines) - 1) / 2) * 17, t, 12, weight=700 if i == 0 else 500)

    def wire(self, net, pts, dot=False):
        # Цвет PE дополнен жёлтым пунктиром; на ч/б печати остаются буквенные метки.
        self.parts.append(S.path(pts, COL[net], sw=2.4))
        if net == "PE":
            self.parts.append(S.path(pts, "#E7C52B", sw=1.1, dash="6 5"))
        if dot:
            x, y = pts[0]
            self.parts.append(f'<circle cx="{x}" cy="{y}" r="4" fill="{COL[net]}"/>')

    def end(self):
        return "".join(self.parts) + "</svg>"


