def fmt(v):
    return format(D(v), ".2f").rstrip("0").rstrip(".").replace(".", ",")


def scenario_rows():
    names = {r[0]: r[1] for r in LOADS}
    names.update(base="Фон", hob_full="Панель 7,4")
    rows = []
    for title, ids, note in SCENARIOS:
        assert len(set(ids) & {"hob", "hob_full"}) <= 1
        total = sum((POWER[i] for i in ids), D("0"))
        kitchen = sum((POWER[i] for i in ids if i in KITCHEN_IDS), D("0"))
        status = "в рабочем ориентире" if total <= TARGET else ("почти предел" if total <= LIMIT else "выше 10 кВт")
        if kitchen > KITCHEN_LIMIT:
            status = "перегрузка QF9 C16"
        composition = " + ".join(f"{names[i]} {fmt(POWER[i])}" for i in ids)
        rows.append([title, composition, fmt(total), fmt(LIMIT-total), status + ". " + note])
    return rows


