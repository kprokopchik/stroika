def related(ids, main=False, title="Связанные документы"):
    return ("links", title, [(BY_ID[i]['name'], ("" if main else "../")+i+"/index.html", BY_ID[i]['about']) for i in ids])


def image_block(name, title, caption, parent_levels=3):
    file = ROOT / 'renders' / 'technical' / name
    if not file.exists():
        return []
    with file.open('rb') as image:
        header=image.read(24)
    width,height=struct.unpack('>II',header[16:24])
    return [("image", title, {"src":"../"*parent_levels+'renders/technical/'+name, "file":str(file), "width":width, "height":height}, caption)]


