class Drawing:
    """Небольшой SVG без JS: одинаковое содержание на сайте и в PDF."""
    def __init__(self, title):
        self.out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 540" role="img" aria-label="{E(title, quote=True)}">',
                    f'<title>{E(title)}</title>', '<rect width="900" height="540" fill="white"/>']

    def rect(self, x, y, w, h, fill='white', stroke=LINE, sw=1.5):
        self.out.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')

    def line(self, x1, y1, x2, y2, color=LINE, sw=1.5, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ''
        self.out.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{color}" stroke-width="{sw}"{d}/>')

    def path(self, d, color=LINE, sw=1.5, fill='none', dash=None):
        extra = f' stroke-dasharray="{dash}"' if dash else ''
        self.out.append(f'<path d="{d}" fill="{fill}" stroke="{color}" stroke-width="{sw}"{extra}/>')

    def text(self, x, y, lines, size=20, color=INK, anchor='start'):
        if isinstance(lines, str):
            lines = [lines]
        self.out.append(f'<text x="{x}" y="{y}" font-family="Arial, sans-serif" font-size="{size}" fill="{color}" text-anchor="{anchor}">')
        for i, line in enumerate(lines):
            self.out.append(f'<tspan x="{x}" dy="{size * 1.25 if i else 0}">{E(line)}</tspan>')
        self.out.append('</text>')

    def label(self, x, y, ly, lines, lx=585):
        self.path(f'M{x} {y} L{lx-22} {ly-7} H{lx-10}')
        self.text(lx, ly, lines)

    def screw(self, x, y):
        self.out.append(f'<circle cx="{x}" cy="{y}" r="3" fill="{INK}"/>')

    def hatch(self, x, y, w, h, fill=CONCRETE):
        self.rect(x, y, w, h, fill)
        for xx in range(int(x)+6, int(x+w)-10, 24):
            self.line(xx, y+h-4, min(xx+16, x+w-3), y+4, '#99a5ab', 1)

    def wool(self, x, y, w, h):
        self.rect(x, y, w, h, WOOL, 'none')
        for yy in range(int(y)+12, int(y+h)-4, 18):
            self.path(f'M{x+4} {yy} Q{x+w*.25} {yy-12} {x+w*.5} {yy} T{x+w-4} {yy}', '#b9ae79', 1)

    def dim(self, x1, y1, x2, y2, label, vertical=False):
        self.line(x1, y1, x2, y2)
        if vertical:
            self.line(x1-6, y1, x1+6, y1)
            self.line(x2-6, y2, x2+6, y2)
            self.text(x1+12, (y1+y2)/2, label, 18)
        else:
            self.line(x1, y1-6, x1, y1+6)
            self.line(x2, y2-6, x2, y2+6)
            self.text((x1+x2)/2, y1-9, label, 18, anchor='middle')

    def finish(self):
        self.text(24, 519, 'Схема принципа · не в масштабе · толщины в мм, если указаны', 16, LINE)
        return ''.join(self.out) + '</svg>'


