def dimensions(p, v):
    # Две внешние цепочки: общая ширина и чистые комнаты + толщины стен.
    dim_h(p, 0, 1171, -115, 0, '1171 · общий размер')
    xs = [0, 325, 333, 600, 610, 1171] if v == 1 else [0, 325, 333, 860, 870, 1171]
    for a, b in zip(xs, xs[1:]):
        if b - a > 10:
            dim_h(p, a, b, -68, 0)
    p.text(585, -142, 'Новые стены 8–12 см; левая детская 8 см · размеры, см', fs=12)
    dim_v(p, 0, 412, -70, 0)
    dim_v(p, 420, 691, -70, 0)
    dim_v(p, 736, 1046, 170, 251)
    dim_h(p, 251, 531, 1105, 1046)
    dim_h(p, 251, 598, 953, 986)
    if v == 1:
        dim_v(p, 0, 520, 515, 600)
        dim_v(p, 0, 410, 1230, 1171)
        dim_v(p, 420, 680, 1230, 1171)
    else:
        dim_v(p, 0, 410, 595, 600)
        dim_v(p, 0, 580, 1230, 1171)
        dim_v(p, 590, 680, 1230, 1171)
    dim_h(p, 870, 1171, 895, 850)
    dim_h(p, 1171, 1345, 930, 850)
    # Внутренние цепочки привязывают двери, а не только габариты комнат.
    for a, b in [(0, 190), (190, 280)]:
        p.dim(a, 398, b, 398, fs=10)
