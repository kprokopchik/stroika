def living_polygon(v):
    # Зона холла x608..1171 в площадь кухни-гостиной НЕ включается.
    top = ([(0, 420), (325, 420), (325, 530), (600, 530)] if v == 1 else
           [(0, 420), (572, 420), (572, 510), (600, 510)])
    return top + [(600, 631), (598, 631), (598, 850), (598, 1011), (531, 1011),
                  (531, 1046), (251, 1046), (251, 736), (330, 736),
                  (330, 691), (0, 691)]



def polygon_area(points):
    return abs(sum(x * points[(i + 1) % len(points)][1] - points[(i + 1) % len(points)][0] * y
                   for i, (x, y) in enumerate(points))) / 2 / 10000


def room_area(v, key):
    pts = ROOM_POLYGONS[v][key]
    x1, y1 = pts[0]
    x2, y2 = pts[2]
    a = polygon_area(pts)
    for a1, b1, a2, b2 in PYLONS:
        a -= max(0, min(x2, a2) - max(x1, a1)) * max(0, min(y2, b2) - max(y1, b1)) / 10000
    return a


def fmt(a):
    return f'≈ {a:.1f} м²'.replace('.', ',')


def dim_h(p, x1, x2, y, wall_y, label=None):
    for x in (x1, x2):
        p.line(x, wall_y, x, y, '#8D979C', .7, 'dims')
    p.dim(x1, y, x2, y, label)


def dim_v(p, y1, y2, x, wall_x, label=None):
    for y in (y1, y2):
        p.line(wall_x, y, x, y, '#8D979C', .7, 'dims')
    p.dim(x, y1, x, y2, label)


def shell(p):
    W = p.wall
    # Фасад: четыре верхних окна, два боковых в гостиной и одно на кухне.
    for x1, x2 in [(-20, 82), (230, 332), (539, 641), (850, 954), (1160, 1196)]:
        W(x1, -36, x2, 0)
    for x1, x2 in [(82, 230), (333, 539), (641, 850), (954, 1160)]:
        p.window(x1, -20, x2, 0)
    for y1, y2 in [(-36, 75), (320, 422), (660, 716)]:
        W(-20, y1, 0, y2)
    for y1, y2 in [(75, 320), (422, 660)]:
        p.window(-20, y1, 0, y2, room='right')
    W(1171, -36, 1196, 680)
    W(-20, 691, 330, 736)
    W(216, 736, 251, 760)
    W(216, 1000, 251, 1071)
    p.window(231, 760, 251, 1000, room='right')
    W(216, 1046, 531, 1071)
    W(531, 1011, 608, 1071)
    W(608, 1046, 895, 1071)
    W(870, 850, 895, 1071)
    W(870, 850, 1370, 875)
    W(1171, 680, 1370, 705)
    W(1345, 705, 1370, 730)
    W(1345, 825, 1370, 875)
    p.door((1370, 730), (1370, 825), (1465, 730))
    p.text(1400, 860, 'Вход', fs=14)


def fixed_cores(p):
    # Рисуем бетон поверх примыкающих новых стен, а не перекрашиваем его в снос/новые стены.
    for rect in PYLONS:
        p.wall(*rect)
    for rect in SHAFTS:
        p.shaft(*rect)
    for i, (x, y) in enumerate(RISERS, 1):
        p.circle(x, y, 10, '#FFFFFF', '#147A82', 1, 'labels')
        p.text(x, y, f'С{i}', fs=8, fill='#147A82', halo=False)


