def polygon_area(points):
    pairs = zip(points, points[1:] + points[:1])
    return abs(sum(x1*y2 - x2*y1 for (x1,y1),(x2,y2) in pairs)) / 20000


def room_area(v, key):
    pts = ROOM_POLYGONS[v][key]
    # Во всех трёх схемах пилоны пересекают спальни только в верхней полосе
    # (глубина до 31 см), где план каждой комнаты прямоугольный.
    left, right = pts[0][0], pts[1][0]
    deducted = sum(max(0, min(right, x2) - max(left, x1)) * y2
                   for x1,y1,x2,y2 in PYLONS if y1 == 0)
    return polygon_area(pts) - deducted / 10000


