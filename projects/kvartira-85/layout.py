    W(-36, 688, 250, 740)          # низ кухни-гостиной
    W(214, 740, 250, 758)          # слева от детской 2
    W(214, 999, 250, 1060)
    W(250, 688, 329, 724)          # выступ в углу детской 2
    W(214, 1041, 958, 1060)        # низ квартиры
    W(933, -43, 958, 716)          # справа, вход 716..820
    W(933, 820, 958, 1060)
    # пилоны и колонны
    W(285, 0, 385, 22)
    W(593, 0, 696, 22)
    W(903, 0, 933, 8)
    W(594, 586, 623, 695)
    W(594, 695, 601, 712)
    W(601, 996, 623, 1041)
    # перегородки
    W(605, 0, 613, 359)            # спальня родителей / детская 1
    W(0, 351, 507, 359)            # спальня / кухня-гостиная, дверь 507..592
    W(592, 351, 613, 359)
    W(753, 412, 933, 419)          # детская 1 / санузел 1
    W(745, 412, 753, 695)          # коридор / санузел 1
    W(745, 688, 762, 695)          # санузел 1 / прихожая, дверь 762..838
