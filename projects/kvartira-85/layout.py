    p.text(1008, 848, "вход", fs=14, weight=700, fill="#C2602A", halo=False)
    p.door((592, 351), (507, 351), (592, 266))          # спальня родителей
    p.door((623, 412), (713, 412), (623, 322))          # детская 1
    p.door((838, 695), (762, 695), (838, 771))          # санузел 1
    p.door((594, 712), (594, 798), (508, 712))          # детская 2
    p.door((725, 823), (650, 823), (725, 748))          # санузел 2, новая дверь

    # коридор, прихожая, гардероб у входа, санузлы
    p.wardrobe(710, 440, 35, 210, "left", "Шкаф 35 см", fs=11)
    p.room_label(655, 560, "Коридор", "≈ 3,6 м²", fs=15)
    p.box(848, 698, 85, 36, "store", "Обувница", fs=10, k3="shoebench")
    p.room_label(800, 790, "Прихожая", "4,2 м²", fs=15)
