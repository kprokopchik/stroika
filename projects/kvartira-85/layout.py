    W(594, 798, 601, 905)          # детская 2 / санузел 2
    W(594, 985, 601, 1041)
    W(601, 823, 650, 830)          # санузел 2 / прихожая, новая дверь 650..725
    W(725, 823, 790, 830)
    N = p.new_wall
    N(594, 905, 601, 985)          # заделан проём из детской 2 в санузел
    N(605, 359, 613, 419)          # выровнен угол детской 1
